<h2>Sizing, Lead Times & Gotchas</h2>
<p>Two mistakes we see every winter with corporate branded hoodies orders:</p>
<ol>
  <li><strong>Underestimating sizes.</strong> SA unisex fits run slim. Order a size larger than your team's t-shirt size, or offer a fitting sample.</li>
  <li><strong>Leaving it to May.</strong> Winter blanks sell out. Place orders in March/April for guaranteed stock and the best pricing.</li>
</ol>
<p>Standard lead time is 7–10 working days for printed hoodies, 10–14 for embroidered orders over 50 units.</p>

