#!/usr/bin/env node
// Build the redirect map for every product URL that the dedupe removed or
// renamed, by matching the backup rows to the surviving rows on product title.
//
//   node scripts/generate-product-redirects.mjs            report + write map
//   node scripts/generate-product-redirects.mjs --report   report only
//
// Env: VITE_SUPABASE_URL, VITE_SUPABASE_PUBLISHABLE_KEY
// Reads the newest .freebuff/backup-* directory.

import { readFileSync, readdirSync, existsSync, writeFileSync, mkdirSync } from "node:fs"
import { join } from "node:path"

const URL = process.env.VITE_SUPABASE_URL
const KEY = process.env.VITE_SUPABASE_PUBLISHABLE_KEY
const H = { apikey: KEY, Authorization: `Bearer ${KEY}` }
const reportOnly = process.argv.includes("--report")

async function fetchAll(table, select) {
  const rows = []
  for (let offset = 0; ; offset += 1000) {
    const r = await fetch(`${URL}/rest/v1/${table}?select=${select}&limit=1000&offset=${offset}`, { headers: H })
    if (!r.ok) throw new Error(`${table} ${r.status}: ${await r.text()}`)
    const b = await r.json()
    rows.push(...b)
    if (b.length < 1000) break
  }
  return rows
}

function latestBackup() {
  const dirs = readdirSync(".freebuff").filter((d) => d.startsWith("backup-")).sort()
  if (!dirs.length) throw new Error("no .freebuff/backup-* directory found")
  return join(".freebuff", dirs[dirs.length - 1])
}

const dir = latestBackup()
console.log(`backup: ${dir}`)
const before = JSON.parse(readFileSync(join(dir, "shop_products.json"), "utf8"))
const after = await fetchAll("shop_products", "id,handle,title,status")

const titleKey = (t) => (t || "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim().replace(/\s+/g, " ")

const afterHandles = new Set(after.map((p) => p.handle))
const afterByTitle = new Map()
for (const p of after) {
  const k = titleKey(p.title)
  if (!afterByTitle.has(k)) afterByTitle.set(k, [])
  afterByTitle.get(k).push(p)
}

const redirects = []
const unresolved = []
for (const p of before) {
  if (afterHandles.has(p.handle)) continue
  const matches = afterByTitle.get(titleKey(p.title)) || []
  if (matches.length === 1) {
    redirects.push({ from: p.handle, to: matches[0].handle })
  } else {
    unresolved.push({ handle: p.handle, title: p.title, matches: matches.length })
  }
}

const unique = new Map()
for (const r of redirects) if (!unique.has(r.from)) unique.set(r.from, r.to)
const list = [...unique.entries()].map(([from, to]) => ({ from, to }))

// how many are chains (an old handle that is itself a target of another redirect)
const targets = new Set(list.map((r) => r.to))
const chains = list.filter((r) => targets.has(r.from))

console.log(`products before: ${before.length}`)
console.log(`products after:  ${after.length}`)
console.log(`handles that disappeared or changed: ${list.length}`)
console.log(`unresolved (no unique title match): ${unresolved.length}`)
for (const u of unresolved.slice(0, 20)) console.log(`   ${u.handle}  (${u.matches} matches)  "${u.title}"`)
if (chains.length) {
  console.log(`\nWARNING: ${chains.length} redirect sources are also redirect targets (chains):`)
  for (const c of chains.slice(0, 20)) console.log(`   ${c.from} -> ${c.to}`)
}

// collapse chains so every old URL points straight at the surviving handle
const finalTarget = new Map(list.map((r) => [r.from, r.to]))
const resolve = (h, seen = new Set()) => {
  let cur = h
  while (finalTarget.has(cur) && !seen.has(cur)) {
    seen.add(cur)
    cur = finalTarget.get(cur)
  }
  return cur
}
const collapsed = list.map((r) => ({ from: r.from, to: resolve(r.from) }))
const collapsedMap = new Map()
for (const r of collapsed) collapsedMap.set(r.from, r.to)
const finalList = [...collapsedMap.entries()].map(([from, to]) => ({ from, to }))

console.log(`\nredirect rules needed: ${finalList.length}`)
const removed = finalList.filter((r) => afterHandles.has(r.to)).length
console.log(`  -> to a live product: ${removed}`)
console.log(`  -> to something else: ${finalList.length - removed}`)

const existing = existsSync("public/_redirects")
  ? readFileSync("public/_redirects", "utf8").split("\n").filter((l) => l.trim() && !l.trim().startsWith("#")).length
  : 0
console.log(`existing _redirects rules: ${existing}`)
console.log(`total if all written to _redirects: ${existing + finalList.length} (Cloudflare Pages static limit is 2000)`)

if (reportOnly) process.exit(0)

// Written outside functions/ on purpose: every file under functions/ becomes a
// route, and this data module should not be reachable over HTTP.
const outDir = "src/generated"
mkdirSync(outDir, { recursive: true })
const body =
  `// AUTO-GENERATED by scripts/generate-product-redirects.mjs - do not edit by hand.\n` +
  `// ${finalList.length} product URLs removed or renamed by the duplicate-catalogue cleanup.\n` +
  `// Consumed by functions/products/[[handle]].ts.\n` +
  `export const PRODUCT_REDIRECTS: Record<string, string> = {\n` +
  finalList.map((r) => `  ${JSON.stringify(r.from)}: ${JSON.stringify(r.to)},`).join("\n") +
  `\n}\n`
writeFileSync(join(outDir, "product-redirects.ts"), body)
console.log(`\nwrote ${join(outDir, "product-redirects.ts")}`)

writeFileSync(
  join(".freebuff", "product-redirects.json"),
  JSON.stringify(Object.fromEntries(finalList.map((r) => [r.from, r.to])), null, 0),
)
console.log(`wrote .freebuff/product-redirects.json`)